/// Magic value stamped onto `dwExtraInfo` by our `SendInput` calls so our own hooks ignore them.
pub const DUPLEX_INJECTED_MAGIC: usize = 0x4450_4C58_4B56_4D01usize;

const WHEEL_DELTA: i16 = 120;
const XBUTTON1: u16 = 1;
const XBUTTON2: u16 = 2;
const MOUSE_MOVE_RELATIVE: u16 = 0x00;

/// Global wait-free SPSC ring buffer written exclusively by the Win32 hook thread and read by `duplexd`.
static WIN_INPUT_RING: SpscRingBuffer<CapturedInputEvent, 4096> = SpscRingBuffer::new();
/// Atomic flag indicating whether `LowLevelKeyboardProc` / `LowLevelMouseProc` should intercept & suppress input.
static WIN_CAPTURE_ACTIVE: AtomicBool = AtomicBool::new(false);
/// Atomic flag latched when the hardware panic sequence trips inside `LowLevelKeyboardProc`.
static WIN_PANIC_LATCHED: AtomicBool = AtomicBool::new(false);
/// Atomic code latched when a mode hotkey (`Ctrl+Alt+P` or `Ctrl+Alt+0..3`) is pressed inside `LowLevelKeyboardProc`.
/// `0` = none, `10` = `CycleNextMode`, `100 + mode_code` = `SelectMode`.
static WIN_HOTKEY_LATCHED: AtomicU8 = AtomicU8::new(0);
/// Thread ID of the dedicated Win32 hook message pump thread.
static WIN_HOOK_THREAD_ID: AtomicU32 = AtomicU32::new(0);

/// Thread-confined panic detector accessed exclusively by the single Win32 hook thread inside `LowLevelKeyboardProc`.
struct HookThreadPanicState(UnsafeCell<PanicDetector>);
unsafe impl Sync for HookThreadPanicState {}

static HOOK_PANIC_DETECTOR: HookThreadPanicState =
    HookThreadPanicState(UnsafeCell::new(PanicDetector::new()));

/// Zero-I/O `WH_KEYBOARD_LL` callback (`< 1 µs` execution path).
unsafe extern "system" fn low_level_keyboard_proc(
    n_code: i32,
    w_param: WPARAM,
    l_param: LPARAM,
) -> LRESULT {
    if n_code >= 0 && WIN_CAPTURE_ACTIVE.load(Ordering::Relaxed) {
        let kb = &*(l_param.0 as *const KBDLLHOOKSTRUCT);

        // Ignore synthetic keystrokes generated by our own SendInput
        if kb.dwExtraInfo == DUPLEX_INJECTED_MAGIC || (kb.flags.0 & LLKHF_INJECTED.0) != 0 {
            return CallNextHookEx(HHOOK::default(), n_code, w_param, l_param);
        }

        let is_extended = (kb.flags.0 & LLKHF_EXTENDED.0) != 0;
        let is_up = (kb.flags.0 & LLKHF_UP.0) != 0;
        let pressed = !is_up;

        if let Some(usage) = windows_scancode_to_hid(kb.scanCode as u16, is_extended) {
            let now_ns = monotonic_now_ns();
            let detector = &mut *HOOK_PANIC_DETECTOR.0.get();

            // Check Hardware Panic Escape Hatch (`Ctrl+Alt+Shift+Backspace` OR `5x Escape in 1.5s`)
            if let Some(trigger_kind) = detector.observe_key(usage, pressed, now_ns) {
                WIN_CAPTURE_ACTIVE.store(false, Ordering::SeqCst);
                WIN_PANIC_LATCHED.store(true, Ordering::SeqCst);
                // Flush remote modifiers on the peer before disconnecting to Mode0Idle
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(
                    HidEvent::ReleaseAllModifiers,
                ));
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::PanicTriggered(trigger_kind));
                let tid = WIN_HOOK_THREAD_ID.load(Ordering::Acquire);
                if tid != 0 {
                    let _ = PostThreadMessageW(tid, WM_QUIT, WPARAM(0), LPARAM(0));
                }
                return CallNextHookEx(HHOOK::default(), n_code, w_param, l_param);
            }

            // Check Global Mode-Switching Hotkeys (`Ctrl+Alt+P` / `Ctrl+Alt+0..3`)
            if let Some(hotkey) = detector.observe_mode_hotkey(usage, pressed) {
                let code = match hotkey {
                    HotkeyAction::CycleNextMode => 10u8,
                    HotkeyAction::SelectMode(m) => 100u8 + m.as_u8(),
                };
                WIN_HOTKEY_LATCHED.store(code, Ordering::Release);
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(
                    HidEvent::ReleaseAllModifiers,
                ));
                return LRESULT(1);
            }

            let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::Key {
                usage,
                pressed,
            }));
            // Suppress local processing on Windows while docked to Debian Laptop
            return LRESULT(1);
        }
    }

    CallNextHookEx(HHOOK::default(), n_code, w_param, l_param)
}

/// Zero-I/O `WH_MOUSE_LL` callback (`< 1 µs` execution path).
unsafe extern "system" fn low_level_mouse_proc(
    n_code: i32,
    w_param: WPARAM,
    l_param: LPARAM,
) -> LRESULT {
    if n_code >= 0 && WIN_CAPTURE_ACTIVE.load(Ordering::Relaxed) {
        let ms = &*(l_param.0 as *const MSLLHOOKSTRUCT);

        if ms.dwExtraInfo == DUPLEX_INJECTED_MAGIC || (ms.flags & LLMHF_INJECTED) != 0 {
            return CallNextHookEx(HHOOK::default(), n_code, w_param, l_param);
        }

        let msg = w_param.0 as u32;
        match msg {
            WM_MOUSEMOVE => {
                // Relative motion deltas are captured at high precision via WM_INPUT Raw Input;
                // return LRESULT(1) here to freeze the local Windows cursor while capturing.
                return LRESULT(1);
            }
            WM_LBUTTONDOWN | WM_LBUTTONUP => {
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseButton {
                    button: HidMouseButton::Left,
                    pressed: msg == WM_LBUTTONDOWN,
                }));
                return LRESULT(1);
            }
            WM_RBUTTONDOWN | WM_RBUTTONUP => {
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseButton {
                    button: HidMouseButton::Right,
                    pressed: msg == WM_RBUTTONDOWN,
                }));
                return LRESULT(1);
            }
            WM_MBUTTONDOWN | WM_MBUTTONUP => {
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseButton {
                    button: HidMouseButton::Middle,
                    pressed: msg == WM_MBUTTONDOWN,
                }));
                return LRESULT(1);
            }
            WM_XBUTTONDOWN | WM_XBUTTONUP => {
                let hiword = ((ms.mouseData >> 16) & 0xFFFF) as u16;
                let button = if hiword == XBUTTON2 {
                    HidMouseButton::Forward
                } else {
                    HidMouseButton::Back
                };
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseButton {
                    button,
                    pressed: msg == WM_XBUTTONDOWN,
                }));
                return LRESULT(1);
            }
            WM_MOUSEWHEEL => {
                let delta = ((ms.mouseData >> 16) & 0xFFFF) as i16;
                let ticks = delta / WHEEL_DELTA;
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseWheel {
                    vertical: if ticks != 0 { ticks } else { delta.signum() },
                    horizontal: 0,
                }));
                return LRESULT(1);
            }
            WM_MOUSEHWHEEL => {
                let delta = ((ms.mouseData >> 16) & 0xFFFF) as i16;
                let ticks = delta / WHEEL_DELTA;
                let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(HidEvent::MouseWheel {
                    vertical: 0,
                    horizontal: if ticks != 0 { ticks } else { delta.signum() },
                }));
                return LRESULT(1);
            }
            _ => {}
        }
    }

    CallNextHookEx(HHOOK::default(), n_code, w_param, l_param)
}

/// Complete Windows 11 `InputBackend` (`SetWindowsHookExW` + `WM_INPUT` + `SendInput`).
pub struct WindowsInputBackend {
    hook_thread: Option<JoinHandle<()>>,
    depressed: DepressedKeyBitmap,
    shm: Option<Arc<crate::shm::ShmWatchdog>>,
    last_hotkey_ns: u64,
    passive_hotkey_held: bool,
}

impl WindowsInputBackend {
    pub fn new(shm: Option<Arc<crate::shm::ShmWatchdog>>) -> Result<Self, PalError> {
        Ok(Self {
            hook_thread: None,
            depressed: DepressedKeyBitmap::new(),
            shm,
            last_hotkey_ns: 0,
            passive_hotkey_held: false,
        })
    }

    fn dispatch_hotkey_to_shm(&mut self, action: HotkeyAction) {
        let now_ns = monotonic_now_ns();
        if now_ns.saturating_sub(self.last_hotkey_ns) < 350_000_000 {
            return;
        }
        self.last_hotkey_ns = now_ns;
        if let Some(ref shm) = self.shm {
            let block = shm.block();
            let target = match action {
                HotkeyAction::CycleNextMode => {
                    let cur =
                        OperationalMode::from_u8_lossy(block.active_mode.load(Ordering::Acquire));
                    cur.cycle_next()
                }
                HotkeyAction::SelectMode(m) => m,
            };
            info!(
                ?action,
                ?target,
                "Global keyboard shortcut triggered on Windows (Ctrl+Alt+P / Ctrl+Alt+0..3)"
            );
            block
                .requested_mode
                .store(target.as_u8(), Ordering::Release);
        }
    }

    fn poll_passive_hotkeys(&mut self) {
        unsafe {
            let ctrl = (GetAsyncKeyState(0x11) as u16 & 0x8000) != 0; // VK_CONTROL
            let alt = (GetAsyncKeyState(0x12) as u16 & 0x8000) != 0; // VK_MENU
            let lwin = (GetAsyncKeyState(0x5B) as u16 & 0x8000) != 0; // VK_LWIN
            let rwin = (GetAsyncKeyState(0x5C) as u16 & 0x8000) != 0; // VK_RWIN

            if !ctrl || !(alt || lwin || rwin) {
                self.passive_hotkey_held = false;
                return;
            }

            let p_down = (GetAsyncKeyState(0x50) as u16 & 0x8000) != 0; // 'P'
            let k0_down = (GetAsyncKeyState(0x30) as u16 & 0x8000) != 0; // '0'
            let k1_down = (GetAsyncKeyState(0x31) as u16 & 0x8000) != 0; // '1'
            let k2_down = (GetAsyncKeyState(0x32) as u16 & 0x8000) != 0; // '2'
            let k3_down = (GetAsyncKeyState(0x33) as u16 & 0x8000) != 0; // '3'

            let any_action_key = p_down || k0_down || k1_down || k2_down || k3_down;
            if !any_action_key {
                self.passive_hotkey_held = false;
                return;
            }
            if self.passive_hotkey_held {
                return;
            }
            self.passive_hotkey_held = true;

            if p_down {
                self.dispatch_hotkey_to_shm(HotkeyAction::CycleNextMode);
            } else if k0_down {
                self.dispatch_hotkey_to_shm(HotkeyAction::SelectMode(OperationalMode::Mode0Idle));
            } else if k1_down {
                self.dispatch_hotkey_to_shm(HotkeyAction::SelectMode(
                    OperationalMode::Mode1PcPrimary {
                        extend_display: false,
                    },
                ));
            } else if k2_down {
                self.dispatch_hotkey_to_shm(HotkeyAction::SelectMode(
                    OperationalMode::Mode1PcPrimary {
                        extend_display: true,
                    },
                ));
            } else if k3_down {
                self.dispatch_hotkey_to_shm(HotkeyAction::SelectMode(
                    OperationalMode::Mode2LaptopPrimary,
                ));
            }
        }
    }

    fn build_scancode_input(scancode: u16, is_extended: bool, pressed: bool) -> INPUT {
        let mut flags = KEYEVENTF_SCANCODE;
        if is_extended {
            flags |= KEYEVENTF_EXTENDEDKEY;
        }
        if !pressed {
            flags |= KEYEVENTF_KEYUP;
        }
        INPUT {
            r#type: INPUT_KEYBOARD,
            Anonymous: INPUT_0 {
                ki: KEYBDINPUT {
                    wVk: VIRTUAL_KEY(0),
                    wScan: scancode,
                    dwFlags: flags,
                    time: 0,
                    dwExtraInfo: DUPLEX_INJECTED_MAGIC,
                },
            },
        }
    }
}

impl InputBackend for WindowsInputBackend {
    fn start_capture(&mut self) -> Result<(), PalError> {
        self.stop_capture()?;
        unsafe {
            (*HOOK_PANIC_DETECTOR.0.get()).reset();
        }
        WIN_PANIC_LATCHED.store(false, Ordering::SeqCst);
        WIN_CAPTURE_ACTIVE.store(true, Ordering::SeqCst);

        let handle = thread::Builder::new()
            .name("duplex-win32-hook".into())
            .spawn(move || unsafe {
                let tid = GetCurrentThreadId();
                WIN_HOOK_THREAD_ID.store(tid, Ordering::Release);

                // Create message-only window to receive unaccelerated WM_INPUT Raw Input deltas
                let msg_hwnd = CreateWindowExW(
                    WINDOW_EX_STYLE(0),
                    windows::core::w!("STATIC"),
                    windows::core::w!("DuplexRawInputSink"),
                    WINDOW_STYLE(0),
                    0,
                    0,
                    0,
                    0,
                    HWND_MESSAGE,
                    None,
                    HINSTANCE::default(),
                    None,
                )
                .unwrap_or(HWND::default());

                if !msg_hwnd.is_invalid() {
                    let rid = RAWINPUTDEVICE {
                        usUsagePage: 0x01, // HID_USAGE_PAGE_GENERIC
                        usUsage: 0x02,     // HID_USAGE_GENERIC_MOUSE
                        dwFlags: RIDEV_INPUTSINK,
                        hwndTarget: msg_hwnd,
                    };
                    let _ = RegisterRawInputDevices(&[rid], size_of::<RAWINPUTDEVICE>() as u32);
                }

                let kb_hook = SetWindowsHookExW(
                    WH_KEYBOARD_LL,
                    Some(low_level_keyboard_proc),
                    HINSTANCE::default(),
                    0,
                );
                let ms_hook = SetWindowsHookExW(
                    WH_MOUSE_LL,
                    Some(low_level_mouse_proc),
                    HINSTANCE::default(),
                    0,
                );

                let mut msg = MSG::default();
                while GetMessageW(&mut msg, HWND::default(), 0, 0).into() {
                    if msg.message == WM_INPUT && WIN_CAPTURE_ACTIVE.load(Ordering::Relaxed) {
                        let mut raw = RAWINPUT::default();
                        let mut raw_size = size_of::<RAWINPUT>() as u32;
                        let copied = GetRawInputData(
                            HRAWINPUT(msg.lParam.0 as *mut core::ffi::c_void),
                            RID_INPUT,
                            Some(&mut raw as *mut RAWINPUT as *mut core::ffi::c_void),
                            &mut raw_size,
                            size_of::<RAWINPUTHEADER>() as u32,
                        );
                        if copied != u32::MAX && raw.header.dwType == RIM_TYPEMOUSE.0 {
                            let mouse = raw.data.mouse;
                            if (mouse.usFlags.0 & MOUSE_MOVE_RELATIVE) == MOUSE_MOVE_RELATIVE {
                                let dx = mouse.lLastX.clamp(i16::MIN as i32, i16::MAX as i32) as i16;
                                let dy = mouse.lLastY.clamp(i16::MIN as i32, i16::MAX as i32) as i16;
                                if dx != 0 || dy != 0 {
                                    let _ = WIN_INPUT_RING.try_push(CapturedInputEvent::Hid(
                                        HidEvent::MouseMoveRel { dx, dy },
                                    ));
                                }
                            }
                        }
                    }
                    let _ = TranslateMessage(&msg);
                    DispatchMessageW(&msg);
                }

                if let Ok(h) = kb_hook {
                    let _ = UnhookWindowsHookEx(h);
                }
                if let Ok(h) = ms_hook {
                    let _ = UnhookWindowsHookEx(h);
                }
                if !msg_hwnd.is_invalid() {
                    let _ = DestroyWindow(msg_hwnd);
                }
                WIN_HOOK_THREAD_ID.store(0, Ordering::Release);
            })
            .map_err(|e| PalError::Input(format!("Failed to spawn Win32 hook thread: {e}")))?;

        self.hook_thread = Some(handle);
        if let Some(ref shm) = self.shm {
            shm.block().input_grab_active.store(true, Ordering::Release);
        }
        info!("Started Windows WH_KEYBOARD_LL + WH_MOUSE_LL + WM_INPUT zero-I/O capture thread");
        Ok(())
    }

    fn stop_capture(&mut self) -> Result<(), PalError> {
        WIN_CAPTURE_ACTIVE.store(false, Ordering::SeqCst);
        let tid = WIN_HOOK_THREAD_ID.load(Ordering::Acquire);
        if tid != 0 {
            unsafe {
                let _ = PostThreadMessageW(tid, WM_QUIT, WPARAM(0), LPARAM(0));
            }
        }
        if let Some(handle) = self.hook_thread.take() {
            let _ = handle.join();
        }
        if let Some(ref shm) = self.shm {
            shm.block()
                .input_grab_active
                .store(false, Ordering::Release);
        }
        Ok(())
    }

    fn poll_captured_events(
        &mut self,
        out: &mut Vec<CapturedInputEvent>,
    ) -> Result<usize, PalError> {
        let count = WIN_INPUT_RING.drain_into(out, 256);
        let hotkey_code = WIN_HOTKEY_LATCHED.swap(0, Ordering::AcqRel);
        if hotkey_code == 10 {
            self.dispatch_hotkey_to_shm(HotkeyAction::CycleNextMode);
        } else if hotkey_code >= 100 {
            let m = OperationalMode::from_u8_lossy(hotkey_code - 100);
            self.dispatch_hotkey_to_shm(HotkeyAction::SelectMode(m));
        }
        if !WIN_CAPTURE_ACTIVE.load(Ordering::Relaxed) {
            self.poll_passive_hotkeys();
        }
        if WIN_PANIC_LATCHED.swap(false, Ordering::AcqRel) {
            warn!("HARDWARE PANIC ESCAPE HATCH TRIPPED ON WINDOWS HOOK");
            self.emergency_panic_release()?;
        }
        Ok(count)
    }

    fn inject_hid_event(&mut self, event: &HidEvent) -> Result<(), PalError> {
        match *event {
            HidEvent::Key { usage, pressed } => {
                if let Some((scancode, is_extended)) = hid_to_windows_scancode(usage) {
                    self.depressed.set_pressed(usage, pressed);
                    if let Some(ref shm) = self.shm {
                        shm.block().set_key_depressed(usage, pressed);
                    }
                    let input = Self::build_scancode_input(scancode, is_extended, pressed);
                    unsafe {
                        let _ = SendInput(&[input], size_of::<INPUT>() as i32);
                    }
                }
            }
            HidEvent::MouseMoveRel { dx, dy } => {
                let input = INPUT {
                    r#type: INPUT_MOUSE,
                    Anonymous: INPUT_0 {
                        mi: MOUSEINPUT {
                            dx: i32::from(dx),
                            dy: i32::from(dy),
                            mouseData: 0,
                            dwFlags: MOUSEEVENTF_MOVE,
                            time: 0,
                            dwExtraInfo: DUPLEX_INJECTED_MAGIC,
                        },
                    },
                };
                unsafe {
                    let _ = SendInput(&[input], size_of::<INPUT>() as i32);
                }
            }
            HidEvent::MouseButton { button, pressed } => {
                let (flags, mouse_data): (MOUSE_EVENT_FLAGS, u32) = match (button, pressed) {
                    (HidMouseButton::Left, true) => (MOUSEEVENTF_LEFTDOWN, 0),
                    (HidMouseButton::Left, false) => (MOUSEEVENTF_LEFTUP, 0),
                    (HidMouseButton::Right, true) => (MOUSEEVENTF_RIGHTDOWN, 0),
                    (HidMouseButton::Right, false) => (MOUSEEVENTF_RIGHTUP, 0),
                    (HidMouseButton::Middle, true) => (MOUSEEVENTF_MIDDLEDOWN, 0),
                    (HidMouseButton::Middle, false) => (MOUSEEVENTF_MIDDLEUP, 0),
                    (HidMouseButton::Back, true) => (MOUSEEVENTF_XDOWN, u32::from(XBUTTON1)),
                    (HidMouseButton::Back, false) => (MOUSEEVENTF_XUP, u32::from(XBUTTON1)),
                    (HidMouseButton::Forward, true) => (MOUSEEVENTF_XDOWN, u32::from(XBUTTON2)),
                    (HidMouseButton::Forward, false) => (MOUSEEVENTF_XUP, u32::from(XBUTTON2)),
                };
                let input = INPUT {
                    r#type: INPUT_MOUSE,
                    Anonymous: INPUT_0 {
                        mi: MOUSEINPUT {
                            dx: 0,
                            dy: 0,
                            mouseData: mouse_data,
                            dwFlags: flags,
                            time: 0,
                            dwExtraInfo: DUPLEX_INJECTED_MAGIC,
                        },
                    },
                };
                unsafe {
                    let _ = SendInput(&[input], size_of::<INPUT>() as i32);
                }
            }
            HidEvent::MouseWheel {
                vertical,
                horizontal,
            } => {
                let mut inputs = Vec::with_capacity(2);
                if vertical != 0 {
                    inputs.push(INPUT {
                        r#type: INPUT_MOUSE,
                        Anonymous: INPUT_0 {
                            mi: MOUSEINPUT {
                                dx: 0,
                                dy: 0,
                                mouseData: (i32::from(vertical) * i32::from(WHEEL_DELTA)) as u32,
                                dwFlags: MOUSEEVENTF_WHEEL,
                                time: 0,
                                dwExtraInfo: DUPLEX_INJECTED_MAGIC,
                            },
                        },
                    });
                }
                if horizontal != 0 {
                    inputs.push(INPUT {
                        r#type: INPUT_MOUSE,
                        Anonymous: INPUT_0 {
                            mi: MOUSEINPUT {
                                dx: 0,
                                dy: 0,
                                mouseData: (i32::from(horizontal) * i32::from(WHEEL_DELTA)) as u32,
                                dwFlags: MOUSEEVENTF_HWHEEL,
                                time: 0,
                                dwExtraInfo: DUPLEX_INJECTED_MAGIC,
                            },
                        },
                    });
                }
                if !inputs.is_empty() {
                    unsafe {
                        let _ = SendInput(&inputs, size_of::<INPUT>() as i32);
                    }
                }
            }
            HidEvent::ReleaseAllModifiers => {
                self.release_all_stuck_keys()?;
            }
        }
        Ok(())
    }

    fn release_all_stuck_keys(&mut self) -> Result<(), PalError> {
        let mut inputs: Vec<INPUT> = Vec::with_capacity(32);

        for usage in self.depressed.drain_pressed() {
            if let Some((sc, ext)) = hid_to_windows_scancode(usage) {
                inputs.push(Self::build_scancode_input(sc, ext, false));
            }
        }
        if let Some(ref shm) = self.shm {
            let mut shm_bmp = shm.block().take_depressed_bitmap();
            for usage in shm_bmp.drain_pressed() {
                if let Some((sc, ext)) = hid_to_windows_scancode(usage) {
                    inputs.push(Self::build_scancode_input(sc, ext, false));
                }
            }
        }
        for usage in ALL_HID_MODIFIER_USAGES {
            if let Some((sc, ext)) = hid_to_windows_scancode(usage) {
                inputs.push(Self::build_scancode_input(sc, ext, false));
            }
        }

        if !inputs.is_empty() {
            unsafe {
                let _ = SendInput(&inputs, size_of::<INPUT>() as i32);
            }
        }
        Ok(())
    }

    fn emergency_panic_release(&mut self) -> Result<(), PalError> {
        let _ = self.stop_capture();
        let _ = self.release_all_stuck_keys();
        if let Some(ref shm) = self.shm {
            let block = shm.block();
            block.panic_latched.store(true, Ordering::SeqCst);
            block.input_grab_active.store(false, Ordering::SeqCst);
            block
                .active_mode
                .store(OperationalMode::Mode0Idle.as_u8(), Ordering::SeqCst);
        }
        Ok(())
    }
}

impl Drop for WindowsInputBackend {
    fn drop(&mut self) {
        let _ = self.stop_capture();
        let _ = self.release_all_stuck_keys();
    }
}
