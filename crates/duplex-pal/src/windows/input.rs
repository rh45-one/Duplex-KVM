//! Windows 11 Low-Level Input PAL (`SetWindowsHookExW` + `WM_INPUT` + Lock-Free SPSC Ring + `SendInput`).
//!
//! Strictly adheres to the Zero-I/O Capture Loop mandate: `LowLevelKeyboardProc` and
//! `LowLevelMouseProc` never allocate, lock, or perform I/O; they evaluate the hardware panic
//! escape hatch inline and push normalized `CapturedInputEvent`s to a wait-free static SPSC ring buffer.

